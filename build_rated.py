def js(v):
    return json.dumps(v, ensure_ascii=False)

def entry(m, kind):
    s = SRC[m['src']]
    ing = []
    for x in s['ing']:
        if any(k in x for k in m.get('skip', [])):
            continue
        # swap: replace a source line (matched by substring) with our own rows,
        # e.g. a seasoning packet with the real spices.
        hit = next((k for k in m.get('swap', {}) if k in x), None)
        ing += m['swap'][hit] if hit else [parse(x)]
    ing = [[q, u, t.replace('rice wine vinegar', 'rice vinegar')] for q, u, t in ing]
    serves = first_int(s['yield']) or 1
    kcal = first_int(s.get('kcal'))
    protein = first_int(s.get('protein'))
    out = {'id': m['id'], 'kind': kind, 'course': m['course']}
    if m.get('cuisine'): out['cuisine'] = m['cuisine']
    out.update({'level': m['level'], 'emoji': m['emoji'], 'title': m['title'], 'time': m['time']})
    if m.get('wait'): out['wait'] = m['wait']
    out['serves'] = serves
    if m.get('servesUnit'): out['servesUnit'] = m['servesUnit']
    keeps = m.get('keeps') or KEEPS.get(m['id'])
    out['tags'] = m['tags'] + (['meal-prep'] if keeps and 'meal-prep' not in m['tags'] else [])
    if keeps: out['keeps'] = keeps
    out['blurb'] = m['blurb']
    if kcal: out['kcal'] = kcal
    if protein and kind == 'human': out['protein'] = protein
    if kcal and m.get('servesUnit'): out['kcalUnit'] = m['servesUnit'].rstrip('s')
    out['rating'] = s['rating']; out['ratings'] = s['count']
    out['source'] = {'site': s.get('site', 'Allrecipes'), 'name': s['name'].strip(), 'url': s['url']}
    if m.get('wow'): out['wow'] = m['wow']
    out['ingredients'] = ing
    out['steps'] = m['steps']
    out['tips'] = m.get('tips', [])
    lines = ['  { ' + ', '.join(f'{k}: {js(v)}' for k, v in out.items() if k not in ('ingredients', 'steps', 'tips', 'source', 'wow')) + ',',
             *([f"    wow: {js(out['wow'])},"] if out.get('wow') else []),
             f"    source: {js(out['source'])},",
             '    ingredients: [' + ', '.join(js(i) for i in ing) + '],',
             '    steps: ' + js(out['steps']) + ',',
             '    tips: ' + js(out['tips']) + ' },']
    return '\n'.join(lines)

